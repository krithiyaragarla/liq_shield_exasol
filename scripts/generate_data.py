"""Generate the deterministic synthetic LiqShield dataset.

Outputs (all synthetic, CC0 / public domain):
  data/*.csv                 - one CSV per table
  sql/03_seed_data.sql       - the same rows as INSERT statements (paste into any Exasol SQL client)

No randomness: the data is hand-designed so every number can be verified by hand.
As-of date is fixed (2026-11-02) so the repo reproduces identically on any day.
"""
from datetime import date, timedelta
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
ASOF = date(2026, 11, 2)
HORIZON_DAYS = 8  # buckets T+0 .. T+7

haircut_rules = pd.DataFrame(
    [
        ("Cash", "NA", 0.0000),
        ("US_Treasury", "AAA", 0.0200),
        ("Corp_Bond_AAA", "AAA", 0.0500),
        ("Corp_Bond_BBB", "BBB", 0.1500),
        ("Equities", "NA", 0.2500),
    ],
    columns=["asset_type", "rating", "haircut_pct"],
)

# amount = current market value (USD). settlement_lag_days = days needed to turn the asset into usable cash
# (cash 0, treasuries/bonds T+1 via repo, equities T+2).
collateral_inventory = pd.DataFrame(
    [
        ("AST-001", "Cash", 5_000_000, False, "Treasury Vault", 0),
        ("AST-002", "US_Treasury", 10_000_000, False, "Custodian A", 1),
        ("AST-003", "Corp_Bond_AAA", 8_000_000, True, "Custodian A", 1),  # pledged elsewhere -> excluded
        ("AST-004", "Corp_Bond_BBB", 2_000_000, False, "Custodian B", 1),
        ("AST-005", "Equities", 3_000_000, False, "Custodian B", 2),
        ("AST-006", "Corp_Bond_AAA", 4_000_000, False, "Custodian A", 1),
    ],
    columns=["asset_id", "asset_type", "amount", "encumbered_flag", "custodian", "settlement_lag_days"],
)

portfolio_positions = pd.DataFrame(
    [
        ("TRD-101", "FX_Swap", "Bank_A", 50_000_000, ASOF + timedelta(days=180)),
        ("TRD-102", "Interest_Rate_Swap", "Bank_B", 100_000_000, ASOF + timedelta(days=720)),
        ("TRD-103", "Options", "Bank_C", 25_000_000, ASOF + timedelta(days=90)),
        ("TRD-104", "FX_Forward", "Bank_A", 30_000_000, ASOF + timedelta(days=30)),
    ],
    columns=["trade_id", "asset_class", "counterparty", "notional", "maturity_date"],
)

# value_day = T+n.  Day 3 contains the designed stress event (Bank_B margin call).
_cf = [
    (0, "In", 1_000_000, "SETTLEMENT", "Bank_A"),
    (0, "Out", 300_000, "FEE", "Exchange"),
    (1, "Out", 500_000, "MARGIN_CALL", "Bank_C"),
    (1, "In", 800_000, "SETTLEMENT", "Bank_C"),
    (2, "Out", 200_000, "MARGIN_CALL", "Bank_A"),
    (2, "Out", 400_000, "SETTLEMENT", "Bank_A"),
    (3, "Out", 15_000_000, "STRESS_MARGIN_CALL", "Bank_B"),
    (3, "Out", 100_000, "FEE", "Exchange"),
    (4, "In", 400_000, "SETTLEMENT", "Bank_A"),
    (4, "Out", 2_500_000, "MARGIN_CALL", "Bank_B"),
    (5, "Out", 3_000_000, "SETTLEMENT", "Bank_C"),
    (5, "In", 1_200_000, "SETTLEMENT", "Bank_B"),
    (6, "Out", 1_000_000, "MARGIN_CALL", "Bank_A"),
    (7, "In", 600_000, "SETTLEMENT", "Bank_C"),
]
cashflow_obligations = pd.DataFrame(
    [(i + 1, ASOF + timedelta(days=d), d, dr, amt, t, cp) for i, (d, dr, amt, t, cp) in enumerate(_cf)],
    columns=["event_id", "action_date", "value_day", "direction", "amount", "obligation_type", "counterparty"],
)

# Funding actions. cost_bps = annualised cost; upfront_fee_bps = one-off fee; available_from_day = lead time.
funding_facilities = pd.DataFrame(
    [
        ("FAC-01", "Intraday central-bank credit line", 5_000_000, 0, 250, 0),
        ("FAC-02", "Committed bank revolver", 8_000_000, 1, 320, 10),
        ("FAC-03", "Overnight repo line", 10_000_000, 1, 450, 5),
        ("FAC-04", "Equity fire-sale", 3_000_000, 2, 1200, 50),
        ("FAC-05", "Parent-company support (uncommitted)", 20_000_000, 4, 600, 0),
    ],
    columns=["facility_id", "facility_name", "limit_amount", "available_from_day", "cost_bps", "upfront_fee_bps"],
)

time_buckets = pd.DataFrame(
    [(d, ASOF + timedelta(days=d)) for d in range(HORIZON_DAYS)], columns=["day_offset", "bucket_date"]
)

TABLES = {
    "HAIRCUT_RULES": haircut_rules,
    "COLLATERAL_INVENTORY": collateral_inventory,
    "PORTFOLIO_POSITIONS": portfolio_positions,
    "CASHFLOW_OBLIGATIONS": cashflow_obligations,
    "FUNDING_FACILITIES": funding_facilities,
    "TIME_BUCKETS": time_buckets,
}


def sql_literal(v) -> str:
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, date):
        return f"'{v.isoformat()}'"
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    return str(v)


def main() -> None:
    (ROOT / "data").mkdir(exist_ok=True)
    lines = ["-- Generated by scripts/generate_data.py (synthetic data, CC0). Run after 02_tables.sql.", ""]
    for name, df in TABLES.items():
        df.to_csv(ROOT / "data" / f"{name.lower()}.csv", index=False)
        cols = ", ".join(c.upper() for c in df.columns)
        for row in df.itertuples(index=False):
            vals = ", ".join(sql_literal(v) for v in row)
            lines.append(f"INSERT INTO {name} ({cols}) VALUES ({vals});")
        lines.append("")
    lines.append("COMMIT;")
    (ROOT / "sql" / "03_seed_data.sql").write_text("\n".join(lines) + "\n")
    print("Wrote", len(TABLES), "CSVs to data/ and sql/03_seed_data.sql")


if __name__ == "__main__":
    main()
