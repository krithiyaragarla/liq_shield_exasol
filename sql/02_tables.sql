-- Portable DDL (Exasol and DuckDB). Statements are separated by semicolons.
CREATE OR REPLACE TABLE HAIRCUT_RULES (
    ASSET_TYPE   VARCHAR(50),
    RATING       VARCHAR(10),
    HAIRCUT_PCT  DECIMAL(6,4)
);

CREATE OR REPLACE TABLE COLLATERAL_INVENTORY (
    ASSET_ID             VARCHAR(20),
    ASSET_TYPE           VARCHAR(50),
    AMOUNT               DECIMAL(18,2),
    ENCUMBERED_FLAG      BOOLEAN,
    CUSTODIAN            VARCHAR(50),
    SETTLEMENT_LAG_DAYS  DECIMAL(3,0)
);

CREATE OR REPLACE TABLE PORTFOLIO_POSITIONS (
    TRADE_ID       VARCHAR(20),
    ASSET_CLASS    VARCHAR(50),
    COUNTERPARTY   VARCHAR(50),
    NOTIONAL       DECIMAL(18,2),
    MATURITY_DATE  DATE
);

CREATE OR REPLACE TABLE CASHFLOW_OBLIGATIONS (
    EVENT_ID         DECIMAL(9,0),
    ACTION_DATE      DATE,
    VALUE_DAY        DECIMAL(3,0),
    DIRECTION        VARCHAR(10),
    AMOUNT           DECIMAL(18,2),
    OBLIGATION_TYPE  VARCHAR(50),
    COUNTERPARTY     VARCHAR(50)
);

CREATE OR REPLACE TABLE FUNDING_FACILITIES (
    FACILITY_ID         VARCHAR(20),
    FACILITY_NAME       VARCHAR(100),
    LIMIT_AMOUNT        DECIMAL(18,2),
    AVAILABLE_FROM_DAY  DECIMAL(3,0),
    COST_BPS            DECIMAL(8,2),
    UPFRONT_FEE_BPS     DECIMAL(8,2)
);

CREATE OR REPLACE TABLE TIME_BUCKETS (
    DAY_OFFSET   DECIMAL(3,0),
    BUCKET_DATE  DATE
);
